#!/usr/bin/env python3
"""gen-metal-blob.py - embed the assembled Metal kernel source into the binary.

Takes the full Metal source assembled by ds4-server (captured once with
DS4_METAL_DUMP_SOURCE=FILE, see README "Building the floppy image") plus the
TileLang tuned config JSON, raw-deflates both (RFC 1951 streams, no gzip
wrapper: the decoder is puff.c from zlib's contrib/puff), and writes
ds4_kernels_gz.c with the byte arrays. ds4_metal.m inflates them at startup,
so the server needs no metal/ or gen/metal/ files on disk.

Usage:
    tools/gen-metal-blob.py FULL_SOURCE.metal TUNED.json > ds4_kernels_gz.c
"""
import sys
import zlib


def raw_deflate(data: bytes) -> bytes:
    co = zlib.compressobj(9, zlib.DEFLATED, -15)
    return co.compress(data) + co.flush()


def emit_array(f, name: str, data: bytes) -> None:
    f.write(f"const unsigned long {name}_len = {len(data)};\n")
    f.write(f"const unsigned char {name}[] = {{\n")
    for i in range(0, len(data), 20):
        f.write(",".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\n")


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = open(sys.argv[1], "rb").read()
    tuned = open(sys.argv[2], "rb").read()
    out = sys.stdout
    out.write("/* Auto-generated by tools/gen-metal-blob.py - do not edit.\n")
    out.write(" * Raw-deflated (RFC 1951) Metal kernel source + TileLang tuned\n")
    out.write(" * config, inflated at startup by puff.c (zlib contrib/puff).\n")
    out.write(" * See README.md 'Building the floppy image from scratch'. */\n")
    out.write("#include <stdint.h>\n")
    emit_array(out, "ds4_kernels_gz", raw_deflate(src))
    out.write(f"const unsigned long ds4_kernels_src_len = {len(src)};\n")
    emit_array(out, "ds4_tuned_gz", raw_deflate(tuned))
    out.write(f"const unsigned long ds4_tuned_src_len = {len(tuned)};\n")


if __name__ == "__main__":
    main()
